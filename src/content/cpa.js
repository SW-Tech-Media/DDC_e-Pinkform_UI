// สร้างบรรทัด XML ของ CPA (CPA 2.0) สำหรับ CodeViewer — accent = แท็กหลัก
export const buildCpaXml = (c, ownPartyId) => [
  { text: '<?xml version="1.0" encoding="UTF-8"?>' },
  { text: `<tp:CollaborationProtocolAgreement tp:cpaid="${c.id}" tp:version="${c.version}">`, accent: true },
  { text: `<tp:Status tp:value="${c.status === "active" ? "agreed" : "proposed"}"/>`, indent: 1 },
  { text: `<tp:End>${c.validTo}T23:59:59+07:00</tp:End>`, indent: 1 },
  { text: "<tp:PartyInfo>", indent: 1, accent: true },
  { text: `<tp:PartyId>${ownPartyId}</tp:PartyId>`, indent: 2 },
  { text: "</tp:PartyInfo>", indent: 1, accent: true },
  { text: "<tp:PartyInfo>", indent: 1, accent: true },
  { text: `<tp:PartyId>${c.partyId}</tp:PartyId>`, indent: 2 },
  { text: `<tp:Certificate tp:certId="${c.certificate}"/>`, indent: 2 },
  { text: `<tp:Service>${c.service}</tp:Service>`, indent: 2 },
  ...c.actions.map((a) => ({ text: `<tp:ThisPartyActionBinding tp:action="${a}"/>`, indent: 2 })),
  { text: `<tp:Endpoint tp:uri="${c.endpoint}" tp:type="allPurpose"/>`, indent: 2 },
  { text: "</tp:PartyInfo>", indent: 1, accent: true },
  { text: "<tp:DocExchange>", indent: 1, accent: true },
  { text: `<tp:ebXMLSenderBinding tp:version="2.0">`, indent: 2 },
  {
    text: `<tp:ReliableMessaging><tp:Retries>${c.retries}</tp:Retries><tp:RetryInterval>PT${c.interval}S</tp:RetryInterval></tp:ReliableMessaging>`,
    indent: 3,
  },
  { text: `<tp:PersistDuration>PT${c.timeout}S</tp:PersistDuration>`, indent: 3 },
  { text: `<tp:SenderNonRepudiation>${c.signature}</tp:SenderNonRepudiation>`, indent: 3 },
  { text: `<tp:SenderDigitalEnvelope>${c.encryption}</tp:SenderDigitalEnvelope>`, indent: 3 },
  { text: "</tp:ebXMLSenderBinding>", indent: 2 },
  { text: "</tp:DocExchange>", indent: 1, accent: true },
  { text: "</tp:CollaborationProtocolAgreement>", accent: true },
];
